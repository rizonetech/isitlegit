// 7z archives made by 7-Zip itself (D02 T04 §7's completion review), so the 7z reader is proven against the format's
// own implementation and not only against archives this repository built: 7-Zip's defaults (LZMA2 for the files, the
// header compressed), for plain files, password-protected files with visible names (-mhe=off) and encrypted names
// (-mhe=on). Each is tested with `7zz t` and its test password before it is kept. The files inside are fictional.
// AES gives each archive a random salt and IV, so a new run writes different bytes with the same structure; the
// archives are kept as base64 in test/fixtures/attachments/seven-zip.ts, with the 7-Zip version that made them.
//
//   node scripts/fixtures/make-7z-real.ts --7zz <path to 7-Zip's 7zz> [--out <file>]
//
// 7zz is 7-Zip's standalone Linux build (https://www.7-zip.org/download.html); nothing here downloads it.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parseArgs } from "node:util";

const PASSWORD = "Test-only-fixture";

function make(zz: string): Record<string, Uint8Array> {
  const dir = mkdtempSync(join(tmpdir(), "make-7z-real-"));
  try {
    writeFileSync(
      join(dir, "invoice.pdf"),
      "%PDF-1.7\n% Fictional invoice INV-0042 from Karoo Fresh Produce (example)\n",
    );
    writeFileSync(join(dir, "statement.xlsx"), "x".repeat(3000));
    const files = [join(dir, "invoice.pdf"), join(dir, "statement.xlsx")];
    const out: Record<string, Uint8Array> = {};
    for (const [name, flags] of [
      ["plain", []],
      ["lockedFiles", [`-p${PASSWORD}`, "-mhe=off"]],
      ["lockedNames", [`-p${PASSWORD}`, "-mhe=on"]],
    ] as const) {
      const archive = join(dir, `${name}.7z`);
      execFileSync(zz, ["a", "-t7z", "-bd", ...flags, archive, ...files], { stdio: "pipe" });
      const tested = execFileSync(zz, ["t", "-bd", `-p${PASSWORD}`, archive], { encoding: "utf8" });
      if (!tested.includes("Everything is Ok")) throw new Error(`7-Zip did not pass its own test of ${name}`);
      out[name] = new Uint8Array(readFileSync(archive));
    }
    return out;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const { values } = parseArgs({
    options: { "7zz": { type: "string" }, out: { type: "string", default: "test/fixtures/attachments/seven-zip.ts" } },
  });
  const zz = values["7zz"];
  if (!zz) throw new Error("give 7-Zip's 7zz with --7zz");
  const version =
    execFileSync(zz, [], { encoding: "utf8" })
      .split("\n")
      .find((l) => l.startsWith("7-Zip")) ?? "";
  const archives = make(zz);
  const b64 = (bytes: Uint8Array) => Buffer.from(bytes).toString("base64");
  const text = [
    "// Generated by scripts/fixtures/make-7z-real.ts (D02 T04 §7); do not edit. 7z archives 7-Zip made with its",
    "// defaults (LZMA2 files, the header LZMA-compressed), each passing `7zz t`, as base64. Fictional files.",
    `// Made by: ${version.trim()}`,
    `export const SEVEN_ZIP_PASSWORD = "${PASSWORD}";`,
    ...Object.entries(archives).map(([name, bytes]) => `export const ${name}7z = "${b64(bytes)}";`),
    "",
  ].join("\n");
  const out = values.out as string;
  writeFileSync(`${out}.tmp`, text);
  renameSync(`${out}.tmp`, out);
  console.log(`wrote ${out}`);
}
