// LZMA fixtures for D02 T04 §7, written as base64 into test/fixtures/attachments/lzma.ts so they load in workerd as
// any module does:
//
// - raw LZMA1 streams of `lzmaInputs()` (test/fixtures/attachments/lzma-inputs.ts), compressed by XZ Utils
//   (`xz --format=raw --lzma1=lc=3,lp=0,pb=2,dict=64KiB`), the format a 7z LZMA coder holds;
// - complete 7z archives whose header is LZMA-compressed, as 7-Zip writes them without -mhe: the start header, a
//   payload of packed file data, the plain header (its main streams' coders and the files' names in UTF-16)
//   compressed and packed after that payload (a nonzero PackPos), and an encoded header (kEncodedHeader) naming that
//   packed range, its LZMA coder and its unpacked size. One archive's files are AES encrypted with visible names; the
//   other's are plain LZMA.
//
// The same bytes on every run.
//
//   node scripts/fixtures/make-7z-lzma.ts [--out <file>]
import { execFileSync } from "node:child_process";
import { renameSync, writeFileSync } from "node:fs";
import { parseArgs } from "node:util";
import { lzmaInputs } from "../../test/fixtures/attachments/lzma-inputs.ts";

export const PROPS = 3 + 0 * 9 + 2 * 45; // lc=3, lp=0, pb=2
const DICT = 64 * 1024;
const LZMA_ID = [0x03, 0x01, 0x01];
const AES_ID = [0x06, 0xf1, 0x07, 0x01];
const PAYLOAD = 48;

const join = (...parts: (Uint8Array | number[])[]) => {
  const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0));
  let at = 0;
  for (const p of parts) {
    out.set(p, at);
    at += p.length;
  }
  return out;
};
const le = (value: number, bytes: number) => {
  const out = new Uint8Array(bytes);
  let v = BigInt(value);
  for (let i = 0; i < bytes; i++) {
    out[i] = Number(v & 0xffn);
    v >>= 8n;
  }
  return out;
};
// A 7z NUMBER (7zFormat.txt): one byte below 0x80, two below 0x4000.
const number = (v: number) => (v < 0x80 ? [v] : [0x80 | (v >> 8), v & 0xff]);
const crc32 = (data: Uint8Array) => {
  let c = 0xffffffff;
  for (const b of data) {
    c ^= b;
    for (let k = 0; k < 8; k++) c = c & 1 ? (c >>> 1) ^ 0xedb88320 : c >>> 1;
  }
  return (c ^ 0xffffffff) >>> 0;
};
const compress = (bytes: Uint8Array) =>
  new Uint8Array(execFileSync("xz", ["--format=raw", `--lzma1=lc=3,lp=0,pb=2,dict=${DICT}`], { input: bytes }));

// The plain header: main streams with one folder of the given coder over the payload, then the files' names.
function plainHeader(coder: number[], names: string[]): Uint8Array {
  const coderRecord = [0x20 | coder.length, ...coder, 5, PROPS, ...le(DICT, 4)];
  const streams = [
    0x04,
    ...[0x06, 0x00, 0x01, 0x09, ...number(PAYLOAD), 0x00],
    ...[0x07, 0x0b, 0x01, 0x00, 0x01, ...coderRecord, 0x0c, ...number(64), 0x00],
    0x00,
  ];
  const utf16 = names.flatMap((n) => [...n].flatMap((ch) => [ch.charCodeAt(0), 0]).concat([0, 0]));
  const files = [0x05, ...number(names.length), 0x11, ...number(utf16.length + 1), 0x00, ...utf16, 0x00];
  return join([0x01], streams, files, [0x00]);
}

// The archive: start header, the payload, the packed header after it (PackPos = the payload's length), the encoded
// header naming that range.
function archive(plain: Uint8Array): Uint8Array {
  const payload = new Uint8Array(PAYLOAD).map((_, i) => (i * 37) & 0xff);
  const packed = compress(plain);
  const coderRecord = [0x20 | LZMA_ID.length, ...LZMA_ID, 5, PROPS, ...le(DICT, 4)];
  const encoded = join([
    0x17,
    ...[0x06, ...number(PAYLOAD), 0x01, 0x09, ...number(packed.length), 0x00],
    ...[0x07, 0x0b, 0x01, 0x00, 0x01, ...coderRecord, 0x0c, ...number(plain.length), 0x00],
    0x00,
  ]);
  const start = join(le(PAYLOAD + packed.length, 8), le(encoded.length, 8), le(crc32(encoded), 4));
  return join([0x37, 0x7a, 0xbc, 0xaf, 0x27, 0x1c, 0, 4], le(crc32(start), 4), start, payload, packed, encoded);
}

const b64 = (bytes: Uint8Array) => Buffer.from(bytes).toString("base64");

if (import.meta.url === `file://${process.argv[1]}`) {
  const { values } = parseArgs({
    options: { out: { type: "string", default: "test/fixtures/attachments/lzma.ts" } },
  });
  const out = values.out as string;
  const streams = Object.entries(lzmaInputs()).map(([name, bytes]) => `  ${name}: "${b64(compress(bytes))}",`);
  const names = ["invoice.pdf", "statement.xlsx"];
  const text = [
    "// Generated by scripts/fixtures/make-7z-lzma.ts (D02 T04 §7); do not edit. Raw LZMA1 streams XZ Utils wrote of",
    "// lzmaInputs(), and 7z archives whose header is LZMA-compressed, as base64.",
    `export const LZMA_PROPS = ${PROPS};`,
    "export const lzmaStreams: Record<string, string> = {",
    ...streams,
    "};",
    `export const encryptedNames7z = "${b64(archive(plainHeader(AES_ID, names)))}";`,
    `export const plainNames7z = "${b64(archive(plainHeader(LZMA_ID, names)))}";`,
    "",
  ].join("\n");
  writeFileSync(`${out}.tmp`, text);
  renameSync(`${out}.tmp`, out);
  console.log(`wrote ${out}`);
}
