// Turns design/tokens/*.json into src/web/styles/tokens.css, the only source of colour, type and spacing for the app
// (D07 T01 §2). Node 24 runs it directly: `node scripts/build-tokens.ts [--out <file>]`.
//
// One `@theme static` block resets Tailwind's own palette, fonts, type scale and spacing multiplier, then declares every
// token in the namespace its utilities read, so a class that is not a token produces no CSS. The light theme is the
// default; the dark theme follows the operating system unless `data-theme` on <html> says otherwise.
import { readFileSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

type Theme = Record<string, string>;
type Role = {
  family: string;
  size: number;
  line: number;
  weight: number;
  tracking?: string;
  case?: string;
  numeric?: string;
};

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = "src/web/styles/tokens.css";
const RESET = [
  "--color-*",
  "--font-*",
  "--text-*",
  "--font-weight-*",
  "--tracking-*",
  "--leading-*",
  "--radius-*",
  "--shadow-*",
  "--spacing-*",
  "--spacing",
];
// Fallbacks for the self-hosted brand families, so text renders before (or without) the web fonts.
const SANS = "ui-sans-serif, system-ui, sans-serif";

function read(name: string): Record<string, unknown> {
  return JSON.parse(readFileSync(join(ROOT, "design/tokens", name), "utf-8"));
}

const rem = (px: number) => `${px / 16}rem`;
const family = (name: string) => (name.includes(",") ? name : `"${name}", ${SANS}`);
const block = (selector: string, lines: string[]) => `${selector} {\n${lines.map((l) => `  ${l}`).join("\n")}\n}`;
const colours = (theme: Theme) => Object.entries(theme).map(([role, value]) => `--color-${role}: ${value};`);

export function buildTokens(): string {
  const colors = read("colors.json") as { themes: { light: Theme; dark: Theme } };
  const spacing = read("spacing.json") as {
    scale: number[];
    radius: Record<string, number>;
    "control-height": Record<string, number>;
    shadow: Record<string, string>;
  };
  const type = read("typography.json") as {
    families: Record<string, string>;
    weights: Record<string, number>;
    scale: number[];
    roles: Record<string, Role>;
  };
  const theme = [
    ...RESET.map((name) => `${name}: initial;`),
    ...colours(colors.themes.light),
    ...spacing.scale.map((px) => `--spacing-${px}: ${px}px;`),
    ...Object.entries(spacing["control-height"]).map(
      ([key, px]) => `--spacing-control${key === "default" ? "" : `-${key}`}: ${px}px;`,
    ),
    ...Object.entries(spacing.radius).map(([key, px]) => `--radius-${key}: ${px}px;`),
    ...Object.entries(spacing.shadow).map(([key, value]) => `--shadow-${key}: ${value};`),
    ...Object.entries(type.families).map(([key, name]) => `--font-${key}: ${family(name)};`),
    // Tailwind's base layer reads these for unstyled text and code; the reset above removed their defaults.
    "--default-font-family: var(--font-text);",
    "--default-mono-font-family: var(--font-mono);",
    ...Object.entries(type.weights).map(([key, weight]) => `--font-weight-${key}: ${weight};`),
    ...type.scale.map((px) => `--text-${px}: ${rem(px)};`),
  ];
  const roles = Object.entries(type.roles).map(([name, role]) =>
    block(`@utility type-${name}`, [
      `font-family: var(--font-${role.family});`,
      `font-size: ${rem(role.size)};`,
      `line-height: ${role.line};`,
      `font-weight: ${role.weight};`,
      ...(role.tracking ? [`letter-spacing: ${role.tracking};`] : []),
      ...(role.case ? [`text-transform: ${role.case};`] : []),
      ...(role.numeric ? [`font-variant-numeric: ${role.numeric};`] : []),
    ]),
  );
  return [
    "/* Generated by scripts/build-tokens.ts from design/tokens/*.json. Do not edit: run pnpm build:css. */",
    block("@theme static", theme),
    block("@media (prefers-color-scheme: dark)", [
      block(':root:not([data-theme="light"])', colours(colors.themes.dark)).replaceAll("\n", "\n  "),
    ]),
    block(':root[data-theme="dark"]', colours(colors.themes.dark)),
    block(':root[data-theme="light"]', colours(colors.themes.light)),
    ...roles,
    "",
  ].join("\n\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const at = process.argv.indexOf("--out");
  const out = join(ROOT, at > 0 ? (process.argv[at + 1] ?? OUT) : OUT);
  const tmp = `${out}.${process.pid}.tmp`;
  writeFileSync(tmp, buildTokens(), "utf-8");
  renameSync(tmp, out);
}
