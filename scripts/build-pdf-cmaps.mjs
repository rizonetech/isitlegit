// Regenerates src/vision/pdf-cmaps.bin and src/vision/pdf-cmaps-index.ts from the pinned pdfjs-dist: the
// packed CMaps the rasteriser hands to the page for CJK and custom-encoded fonts, since the Worker bundle
// cannot serve the package's cmaps directory. Run after a pdfjs-dist upgrade: node scripts/build-pdf-cmaps.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = "node_modules/pdfjs-dist/cmaps";
const names = readdirSync(dir).filter((name) => name.endsWith(".bcmap")).sort();
const chunks = [];
const index = {};
let offset = 0;
for (const name of names) {
  const bytes = readFileSync(`${dir}/${name}`);
  index[name] = [offset, bytes.length];
  chunks.push(bytes);
  offset += bytes.length;
}
writeFileSync("src/vision/pdf-cmaps.bin", Buffer.concat(chunks));
writeFileSync(
  "src/vision/pdf-cmaps-index.ts",
  `// Generated by scripts/build-pdf-cmaps.mjs from pdfjs-dist's packed CMaps (licence in NOTICE.md). Do not edit.\nexport const CMAP_INDEX: Record<string, readonly [number, number]> = ${JSON.stringify(index)};\n`,
);
console.log(`wrote ${names.length} cmaps, ${offset} bytes`);
