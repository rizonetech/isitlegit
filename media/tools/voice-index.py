#!/usr/bin/env python3
"""Write media/src/data/voice.ts: the narration clips each video plays, from media/out/voice/<video>/manifest.json, and
the music and sound effects, from media/out/sound/manifest.json (tools/sound.py).

The render scripts run it first. A video with no manifest renders silent. A manifest that misses a segment, or whose
clip says other words than media/data/narration/<video>.json now does, stops the render (exit 1) and names the
voiceover.py run that fixes it, so a scene never plays another scene's words. Without a sound manifest the videos
have no music or effects; one older than media/data/sound.json stops the render the same way.

Every file also gets a gain: its integrated loudness is measured once with Remotion's ffmpeg (cached by content
hash in media/out/levels.json) and the gain brings it to REFERENCE, so every clip and sound enters the mix at the
same level and src/kit/ sets only their balance. The module is git-ignored, like stats.json, and replaced atomically.
"""

import hashlib
import importlib.util
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

MEDIA = Path(__file__).resolve().parent.parent
OUT = MEDIA / "src" / "data" / "voice.ts"
LEVELS = MEDIA / "out" / "levels.json"
# The logo animation's sound, which opens every explainer (src/videos/LogoReveal.tsx), gain-matched like the rest.
LOGO = MEDIA.parent / "design" / "brand" / "videos" / "logo_animation.mp4"
FFMPEG = [str(MEDIA / "node_modules" / ".bin" / "remotion"), "ffmpeg"]
# The level every file is brought to before the mix: low enough that narration peaks stay under full scale before
# mastering lifts the whole video to -14 LUFS.
REFERENCE = -19.0
SPEC = importlib.util.spec_from_file_location("voiceover", Path(__file__).with_name("voiceover.py"))
vo = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(vo)
SOUND_SPEC = importlib.util.spec_from_file_location("sound", Path(__file__).with_name("sound.py"))
snd = importlib.util.module_from_spec(SOUND_SPEC)
SOUND_SPEC.loader.exec_module(snd)


def clips(video: str) -> list[dict] | None:
    """The video's clips in segment order, None when it has no voice yet; ValueError when the voice is stale."""
    _, texts = vo.load(video)
    manifest = vo.OUT / video / "manifest.json"
    if not manifest.exists():
        return None
    by_index = {c["index"]: c for c in json.loads(manifest.read_text()).get("clips", [])}
    rerun = f"run python3 media/tools/voiceover.py {video}"
    for i, text in enumerate(texts):
        clip = by_index.get(i)
        if clip is None or not (vo.OUT / video / clip["file"]).exists():
            raise ValueError(f"video {video}: segment {i:02d} has no clip; {rerun}")
        if clip.get("text") != text:
            raise ValueError(f"video {video}: clip {clip['file']} does not match the narration text; {rerun}")
    return [by_index[i] for i in range(len(texts))]


def sounds() -> dict[str, dict]:
    """Every music and sfx file by name, {} when none were made yet; ValueError when one is stale or missing."""
    manifest = snd.OUT / "manifest.json"
    if not manifest.exists():
        return {}
    made = json.loads(manifest.read_text()).get("files", {})
    found = {}
    for kind, name, e in snd.entries(json.loads(snd.SPEC.read_text())):
        f = made.get(name)
        if not f or f.get("digest") != snd.digest(kind, e) or not (snd.OUT / f["file"]).exists():
            raise ValueError(f"sound {name} is missing or older than data/sound.json; run python3 media/tools/sound.py")
        found[name] = f
    return found


def loudness(path: Path) -> float:
    """Integrated loudness in LUFS (EBU R128), measured by ffmpeg's loudnorm without writing anything."""
    r = subprocess.run([*FFMPEG, "-hide_banner", "-nostats", "-i", str(path), "-vn", "-af", "loudnorm=print_format=json", "-c:a", "pcm_s16le", "-f", "null", "-"], capture_output=True, text=True)
    found = re.search(r'"input_i"\s*:\s*"(-?[0-9.]+|-inf)"', r.stderr)
    if r.returncode or not found:
        raise ValueError(f"cannot measure the loudness of {path.name}")
    return float(found.group(1)) if found.group(1) != "-inf" else -70.0


def gains(paths: list[Path]) -> dict[Path, float]:
    """Each file's linear gain to REFERENCE, measuring only files whose content is new since the last render."""
    cache = json.loads(LEVELS.read_text()) if LEVELS.exists() else {}
    found = {}
    for path in paths:
        key = hashlib.sha256(path.read_bytes()).hexdigest()[:16]
        if key not in cache:
            cache[key] = loudness(path)
        found[path] = round(10 ** ((REFERENCE - cache[key]) / 20), 4)
    write(json.dumps(cache, indent=2) + "\n", LEVELS)
    return found


def module(voices: dict[str, list[dict]], sound: dict[str, dict], logo_gain: float = 1.0) -> str:
    lines = ["// Generated by media/tools/voice-index.py before every render; git-ignored, never edited.", ""]
    entries = []
    for video, cs in voices.items():
        name = re.sub(r"\W", "_", video)  # an identifier: "01-hook" imports as v01_hook_00
        for c in cs:
            lines.append(f'import v{name}_{c["index"]:02d} from "../../out/voice/{video}/{c["file"]}";')
        entries.append(f'  "{video}": [' + ", ".join(f'{{ src: v{name}_{c["index"]:02d}, seconds: {c["seconds"]}, gain: {c["gain"]} }}' for c in cs) + "],")
    ident = {name: re.sub(r"\W", "_", name) for name in sound}  # "demo-bed" imports as s_demo_bed
    for name, f in sound.items():
        lines.append(f'import s_{ident[name]} from "../../out/sound/{f["file"]}";')
    lines += ["", "export const VOICE: Record<string, { src: string; seconds: number; gain: number }[]> = {", *entries, "};", ""]
    lines += ["export const SOUND: Record<string, { src: string; seconds: number; gain: number }> = {"]
    lines += [f'  {json.dumps(name)}: {{ src: s_{ident[name]}, seconds: {f["seconds"]}, gain: {f["gain"]} }},' for name, f in sound.items()]
    lines += ["};", "", f"export const LOGO_GAIN = {logo_gain};", ""]
    return "\n".join(lines)


def write(text: str, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=out.parent, prefix=f".{out.name}-")
    with os.fdopen(fd, "w") as fh:
        fh.write(text)
    os.replace(tmp, out)


def main(argv: list[str] | None = None) -> int:
    """Index every video's voice, or only the videos named in argv (a render of one video then does not depend on
    another video's stale clips; the videos left out render silent until their own render indexes them)."""
    only = set(argv or [])
    voices, failures = {}, []
    for path in sorted(vo.NARRATION.glob("*.json")):
        if only and path.stem not in only:
            continue
        try:
            found = clips(path.stem)
        except (OSError, ValueError, KeyError, json.JSONDecodeError) as exc:
            failures.append(str(exc))
            continue
        if found is not None:
            voices[path.stem] = found
    try:
        sound = sounds()
    except (OSError, ValueError, KeyError, json.JSONDecodeError) as exc:
        failures.append(str(exc))
    if not failures:
        files = [vo.OUT / v / c["file"] for v, cs in voices.items() for c in cs] + [snd.OUT / f["file"] for f in sound.values()] + [LOGO]
        try:
            level = gains(files)
        except (OSError, ValueError) as exc:
            failures.append(str(exc))
    for f in failures:
        print(f"voice-index: {f}", file=sys.stderr)
    if failures:
        return 1
    voices = {v: [{**c, "gain": level[vo.OUT / v / c["file"]]} for c in cs] for v, cs in voices.items()}
    sound = {n: {**f, "gain": level[snd.OUT / f["file"]]} for n, f in sound.items()}
    write(module(voices, sound, level[LOGO]), OUT)
    silent = sorted(p.stem for p in vo.NARRATION.glob("*.json") if p.stem not in voices)
    print(f"voice-index: voiced {', '.join(voices) or 'none'}; silent {', '.join(silent) or 'none'}; sound {', '.join(sound) or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
