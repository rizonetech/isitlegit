// pnpm capture:index: write media/src/data/demo-capture.ts, the newest capture the demo composition plays (D09 T02 §4).
// Like src/data/voice.ts (tools/voice-index.py), it is generated, git-ignored and replaced atomically: it imports each
// beat's video so Remotion's bundler serves it, and inlines the manifest's marks and boxes, so every zoom lands on the
// live page's own pixels and every time on screen is measured. With no capture, the module exports null and the demo
// renders its cards alone. CAPTURE_DIR picks a capture other than the newest.
import { existsSync, readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const MEDIA = new URL("..", import.meta.url).pathname;
const CAPTURES = join(MEDIA, "out", "capture");
const OUT = join(MEDIA, "src", "data", "demo-capture.ts");

type Manifest = {
  capturedAt: string;
  liveCommit: string | null;
  beats: { beat: string; video: string | null; caseId: string | null; marks: Record<string, number>; boxes: Record<string, unknown> }[];
  skipped: { beat: string; reason: string }[];
};

/** The newest capture folder whose manifest skipped nothing, or the one CAPTURE_DIR names. */
export function pick(root = CAPTURES): string | null {
  if (process.env.CAPTURE_DIR) return process.env.CAPTURE_DIR;
  if (!existsSync(root)) return null;
  for (const dir of readdirSync(root).sort().reverse()) {
    const path = join(root, dir, "manifest.json");
    if (!existsSync(path)) continue;
    const m = JSON.parse(readFileSync(path, "utf8")) as Manifest;
    if (!m.skipped.length && m.beats.every((b) => b.video && existsSync(b.video))) return join(root, dir);
  }
  return null;
}

export function moduleFor(dir: string | null, outFile = OUT): string {
  const head = "// Generated by media/capture/index.ts before every demo render; git-ignored, never edited.\n";
  if (!dir) return `${head}\nexport const CAPTURE = null;\n`;
  const m = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8")) as Manifest;
  const imports: string[] = [];
  const beats = m.beats.map((b, i) => {
    const name = `clip${i}`;
    imports.push(`import ${name} from ${JSON.stringify(relative(join(outFile, ".."), b.video as string))};`);
    return `    ${JSON.stringify(b.beat)}: { src: ${name}, caseId: ${JSON.stringify(b.caseId)}, marks: ${JSON.stringify(b.marks)}, boxes: ${JSON.stringify(b.boxes)} },`;
  });
  return `${head}\n${imports.join("\n")}\n\nexport const CAPTURE = {\n  capturedAt: ${JSON.stringify(m.capturedAt)},\n  liveCommit: ${JSON.stringify(m.liveCommit)},\n  beats: {\n${beats.join("\n")}\n  },\n} as const;\n`;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop() as string)) {
  const dir = pick();
  writeFileSync(`${OUT}.tmp`, moduleFor(dir));
  renameSync(`${OUT}.tmp`, OUT);
  console.log(dir ? `demo capture: ${relative(MEDIA, dir)}` : "demo capture: none (cards only)");
}
